import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const credentials = () => JSON.parse(readFileSync(new URL('../../.build/testdb/browser.json', import.meta.url), 'utf8')) as {
    username: string;
    password: string;
};
test('accounts, scoped access and source-worker enrollment', async ({ page, browser }, testInfo) => {
    const pageErrors: string[] = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    const admin = credentials();
    const suffix = Math.random().toString(36).slice(2, 10);
    const username = 'engineer.' + suffix;
    const password = 'A fictional browser password 2026';
    await page.goto('/login');
    await expect(page.getByRole('heading', { name: 'Sign in to your workspace' })).toBeVisible();
    await page.getByLabel('Username', { exact: true }).fill(admin.username);
    await page.getByLabel('Password', { exact: true }).fill(admin.password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Your projects' })).toBeVisible();
    await page.getByRole('button', { name: 'Local accounts', exact: true }).click();
    const create = page.getByRole('heading', { name: 'Create a local account' }).locator('..');
    await create.getByLabel('Username', { exact: true }).fill(username);
    await create.getByLabel('Display name', { exact: true }).fill('Engineer ' + suffix);
    await create.getByRole('button', { name: 'Create account', exact: true }).click();
    const row = page.getByRole('row').filter({ hasText: username });
    await expect(row).toBeVisible();
    await row.getByRole('button', { name: 'Setup code', exact: true }).click();
    const code = (await page.locator('.once-visible code').innerText()).trim();
    const context = await browser.newContext({ ignoreHTTPSErrors: true, baseURL: 'https://localhost:5174' });
    const engineer = await context.newPage();
    engineer.on('pageerror', error => pageErrors.push(error.message));
    await engineer.goto('/account/setup');
    await engineer.getByLabel('Setup code', { exact: true }).fill(code);
    await engineer.getByLabel('New password', { exact: true }).fill(password);
    await engineer.getByLabel('Confirm password', { exact: true }).fill(password);
    await engineer.getByRole('button', { name: 'Save password' }).click();
    await expect(engineer.getByRole('heading', { name: 'Password saved' })).toBeVisible();
    await engineer.getByRole('link', { name: 'Go to sign in' }).click();
    await engineer.getByLabel('Username', { exact: true }).fill(username);
    await engineer.getByLabel('Password', { exact: true }).fill(password);
    await engineer.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(engineer.getByRole('heading', { name: 'No projects assigned yet' })).toBeVisible();
    await expect(engineer.getByRole('button', { name: 'Local accounts', exact: true })).toHaveCount(0);
    const org = 'Engineering ' + suffix;
    const addOrg = page.getByRole('heading', { name: 'Add an organization' }).locator('..');
    await addOrg.getByLabel('Name', { exact: true }).fill(org);
    await addOrg.getByRole('button', { name: 'Create organization', exact: true }).click();
    await expect(page.getByLabel('Organization', { exact: true })).toContainText(org);
    await page.getByLabel('Organization', { exact: true }).selectOption({ label: org });
    await page.getByRole('button', { name: 'Projects', exact: true }).click();
    await page.getByLabel('Project name', { exact: true }).fill('Payments');
    await page.getByRole('button', { name: 'Create project', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Payments', exact: true })).toBeVisible();
    await page.getByLabel('New environment for Payments', { exact: true }).fill('Development');
    await page.getByRole('button', { name: 'Add', exact: true }).click();
    await expect(page.locator('.environment')).toContainText('Development');
    await page.getByRole('button', { name: 'Teams & access', exact: true }).click();
    await page.getByLabel('Local username', { exact: true }).fill(username);
    await page.getByRole('button', { name: 'Create invitation', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Invitation sent' })).toBeVisible();
    await engineer.reload();
    await engineer.getByRole('button', { name: 'Accept invitation', exact: true }).click();
    await expect(engineer.getByRole('heading', { name: 'No projects assigned yet' })).toBeVisible();
    await page.getByLabel('Team name', { exact: true }).fill('Engineers');
    await page.getByRole('button', { name: 'Create team', exact: true }).click();
    await page.getByLabel('Member to add to Engineers', { exact: true }).selectOption({ label: 'Engineer ' + suffix });
    await page.getByRole('button', { name: 'Add member', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Team member added' })).toBeVisible();
    const grant = page.locator('.grant-form');
    await grant.getByLabel('Team', { exact: true }).selectOption({ label: 'Engineers' });
    await grant.getByLabel('Project', { exact: true }).selectOption({ label: 'Payments' });
    await grant.getByLabel('Environment', { exact: true }).selectOption({ label: 'Development' });
    await grant.getByRole('button', { name: 'Grant access', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Access granted' })).toBeVisible();
    await engineer.reload();
    await expect(engineer.getByRole('heading', { name: 'Payments', exact: true })).toBeVisible();
    await expect(engineer.locator('.environment')).toContainText('Development');
    await engineer.screenshot({ path: testInfo.outputPath('assigned-projects.png'), fullPage: true });
    await page.getByRole('button', { name: 'Revoke', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Access revoked' })).toBeVisible();
    await engineer.reload();
    await expect(engineer.getByRole('heading', { name: 'No projects assigned yet' })).toBeVisible();
    // Phase-2 administration stays local: create a pool and a paused worker,
    // reveal its credential once, then leave the page without retaining it.
    await page.getByRole('button', { name: 'Sources & workers', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Configured resources', exact: true })).toBeVisible();
    const poolName = 'Local source pool ' + suffix;
    const pool = page.getByRole('heading', { name: 'Add a worker pool', exact: true }).locator('..');
    await pool.getByLabel('Pool name', { exact: true }).fill(poolName);
    await pool.getByRole('button', { name: 'Add pool', exact: true }).click();
    await expect(page.locator('.row strong').filter({ hasText: poolName })).toBeVisible();
    const worker = page.getByRole('heading', { name: 'Enroll a worker', exact: true }).locator('..');
    await worker.getByLabel('Worker name', { exact: true }).fill('Source worker ' + suffix);
    await worker.getByLabel('Pool', { exact: true }).selectOption({ label: poolName });
    await worker.getByRole('button', { name: 'Enroll worker', exact: true }).click();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveValue(/"worker_id"/);
    // Leave while the credential is still visible: dismissing it first would
    // conceal broken cleanup when navigating between the two settings views.
    await page.getByRole('button', { name: 'Source checks', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Source checks', level: 1 })).toBeVisible();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Sources & workers', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Configured resources', exact: true })).toBeVisible();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Replace credential', exact: true }).click();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveValue(/"worker_id"/);
    await page.getByRole('button', { name: 'Dismiss credential', exact: true }).click();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('source-settings.png'), fullPage: true });
    await page.getByRole('button', { name: 'Source checks', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Source checks', level: 1 })).toBeVisible();
    await expect(page.getByText('No source checks yet.', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Worker credential', { exact: true })).toHaveCount(0);
    // Sign-out clears protected contents, then returning never repeats a mutation.
    await engineer.getByRole('button', { name: 'Sign out', exact: true }).click();
    await expect(engineer.getByRole('heading', { name: 'Sign in to your workspace' })).toBeVisible();
    await context.close();
    expect(pageErrors).toEqual([]);
});
